"""What a bar-driven strategy offers its runner. Only the wave setup strategy implements it for now; the
opening-range strategy is not built on it."""

from typing import Protocol


class Strategy(Protocol):
    def start_session(self, session, bars_by_ticker): ...

    def restore(self, state) -> bool: ...

    def prepare(self): ...

    def catch_up(self): ...

    def add_bar(self, ticker, bar) -> bool: ...

    def on_bar_exits(self, ticker, bar): ...

    def on_bar_shorts(self, ticker, bar): ...

    def takes_entries(self, bar_time) -> bool: ...

    def submit_evaluations(self, ticker, bar_time): ...

    def on_pre_open(self): ...

    def on_close_decision(self): ...

    def close_leftovers(self): ...

    def wait_pending(self): ...

    def state(self) -> dict: ...
