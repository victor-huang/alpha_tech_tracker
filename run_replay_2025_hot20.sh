# Build TODO list (skip already-done)
TODO=()
for D in "${ALL_DAYS[@]}"; do
  if is_done "$D"; then
    echo "  skip $D"
  else
    TODO+=("$D")
  fi
done

total=${#TODO[@]}
echo ""
echo "=== Phase 2: $total dates to run (max $MAX_PARALLEL parallel) ==="
echo "    Log dir: $LOG_DIR"
echo ""

i=0
batch_num=1
while [ $i -lt $total ]; do
  batch=()
  for k in $(seq 0 $((MAX_PARALLEL-1))); do
    idx=$((i+k))
    [ $idx -lt $total ] && batch+=("${TODO[$idx]}")
  done
  first="${batch[0]}"
  last="${batch[${#batch[@]}-1]}"
  echo "--- Batch $batch_num: $first → $last (${#batch[@]} dates) ---"
  PIDS=()
  for D in "${batch[@]}"; do
    replay_one "$D" &
    PIDS+=($!)
  done
  for j in "${!PIDS[@]}"; do
    wait "${PIDS[$j]}" && echo "  OK  ${batch[$j]}" || echo "  ERR ${batch[$j]}"
  done
  i=$((i + ${#batch[@]}))
  batch_num=$((batch_num + 1))
done

echo ""
echo "=== All done. Logs: $(ls $LOG_DIR/*.log | wc -l) ==="
